// t(id, vars, g): g is "m" or "f", the gender of the player the line is about or addressed to
export function t(id: string, vars?: Record<string, any> | null, g?: string) {
  const e = COPY[id]; if (!e) return id;
  const s = (g === "f" && e[1]) ? e[1] : e[0];
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars && vars[k] != null) ? vars[k] : "");
}
export const countLabel = (n: number) => n === 1 ? t("lobby.count1") : n === 2 ? t("lobby.count2") : t("lobby.countFew", { n });
